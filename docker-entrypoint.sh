#!/bin/sh
set -e

# ==========================================================================
# 邻里鲜生 · Docker 启动脚本
# 首次启动自动初始化数据库 + 种子数据
# ==========================================================================

DB_DIR=$(dirname "$DB_PATH")
mkdir -p "$DB_DIR"

INIT_FLAG="$DB_DIR/.initialized"

if [ ! -f "$INIT_FLAG" ]; then
    echo "=========================================="
    echo "  首次启动: 初始化数据库..."
    echo "=========================================="
    node server/seed.js
    touch "$INIT_FLAG"
    echo "  数据库初始化完成"
    echo "=========================================="
else
    echo "[邻里鲜生] 数据库已初始化, 跳过种子数据"
fi

echo "[邻里鲜生] 启动服务: $@"
exec "$@"
